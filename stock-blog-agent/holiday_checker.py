def get_korean_now():
    """현재 대한민국 표준시(KST, UTC+9) 기준 datetime 반환"""
    return datetime.now(timezone.utc).astimezone(KST)

def get_korean_today():
    """현재 대한민국 표준시(KST, UTC+9) 기준 오늘 날짜(date) 반환"""
    return get_korean_now().date()

