def _to_date(dt=None):
    """datetime 또는 date 객체를 KST 기준 date로 정규화 (None인 경우 현재 한국 날짜)"""
    if dt is None:
        return get_korean_today()
    if isinstance(dt, datetime):
        if dt.tzinfo is not None:
            return dt.astimezone(KST).date()
        return dt.date()
    if isinstance(dt, date):
        return dt
    if isinstance(dt, str):
        return datetime.strptime(dt[:10], "%Y-%m-%d").date()
    raise TypeError(f"지원하지 않는 날짜 형식입니다: {type(dt)}")

def is_weekend(dt=None):
    """
    해당 날짜가 주말(토요일 또는 일요일)인지 확인합니다.
    반환값: (bool, 요일설명)
    """
    d = _to_date(dt)
    weekday = d.weekday()  # 0=월, 1=화, 2=수, 3=목, 4=금, 5=토, 6=일
    if weekday == 5:
        return True, "토요일 (주말)"
    if weekday == 6:
        return True, "일요일 (주말)"
    return False, ""

def is_public_holiday(dt=None):
    """
    해당 날짜가 공휴일, 대체공휴일, 선거일, 또는 증시 휴장일인지 확인합니다.
    반환값: (bool, 공휴일명칭)
    """
    d = _to_date(dt)
    date_str = d.strftime("%Y-%m-%d")

    # 1. 2024~2030+ 데이터베이스에서 직접 검색
    if date_str in KNOWN_HOLIDAYS:
        return True, KNOWN_HOLIDAYS[date_str]

    # 2. 미래/과거 연도 대비 기본 양력 고정 공휴일 계산 (DB에 없는 연도 대비)
    month_day = (d.month, d.day)
    fixed_holidays = {
        (1, 1): "신정",
        (3, 1): "3·1절",
        (5, 1): "근로자의 날 (증시 휴장)",
        (5, 5): "어린이날",
        (6, 6): "현충일",
        (8, 15): "광복절",
        (10, 3): "개천절",
        (10, 9): "한글날",
        (12, 25): "성탄절",
    }
    if month_day in fixed_holidays:
        return True, fixed_holidays[month_day]

    # 3. 양력 공휴일 대체공휴일 자동 계산 (3·1절, 어린이날, 광복절, 개천절, 한글날, 성탄절)
    if d.weekday() == 0:  # 월요일인 경우
        sat_before = d - timedelta(days=2)
        sun_before = d - timedelta(days=1)
        for cand, desc in [(sun_before, "일요일"), (sat_before, "토요일")]:
            cand_md = (cand.month, cand.day)
            if cand_md in [(3, 1), (5, 5), (8, 15), (10, 3), (10, 9), (12, 25)]:
                return True, f"{fixed_holidays[cand_md]} 대체공휴일"

    # 4. 연말 마지막 평일(12월 31일 또는 직전 금요일) 증시 폐장일
    if d.month == 12 and d.day >= 29:
        last_day = date(d.year, 12, 31)
        offset = 0
        if last_day.weekday() == 5:  # 토
            offset = 1
        elif last_day.weekday() == 6:  # 일
            offset = 2
        krx_close_date = last_day - timedelta(days=offset)
        if d == krx_close_date:
            return True, "연말 증시 휴장일 (납회일)"

    return False, ""

def is_market_closed(dt=None):
    """
    주말 또는 공휴일(증시 휴장일) 여부를 종합 판별합니다.
    반환값: (bool, 사유 문자열)
    """
    d = _to_date(dt)

    # 1. 주말 체크
    weekend_res, weekend_desc = is_weekend(d)
    
    # 2. 공휴일 체크
    holiday_res, holiday_desc = is_public_holiday(d)

    if weekend_res and holiday_res:
        return True, f"{weekend_desc} / {holiday_desc}"
    if weekend_res:
        return True, weekend_desc
    if holiday_res:
        return True, f"공휴일 ({holiday_desc})"

    weekday_names = ["월요일", "화요일", "수요일", "목요일", "금요일", "토요일", "일요일"]
    return False, f"정상 영업일 ({weekday_names[d.weekday()]})"

def get_next_business_day(dt=None):
    """다음 영업일(주말 및 공휴일이 아닌 날)을 반환합니다."""
    d = _to_date(dt) + timedelta(days=1)
    while True:
        closed, _ = is_market_closed(d)
        if not closed:
            return d
        d += timedelta(days=1)

